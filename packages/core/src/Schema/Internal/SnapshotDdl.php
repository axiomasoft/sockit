<?php

declare(strict_types=1);

namespace SocKit\Schema\Internal;

use Packman\Attributes\Internal;

/** PostgreSQL initial-install program. Only validated data predicates, never module SQL. */
#[Internal]
final class SnapshotDdl
{
    /** @param array<string, mixed> $draft
     * @return array{up:list<string>, down:list<string>, tables:list<string>} */
    public function compile(array $draft, PhysicalSchema $physical): array
    {
        $data = $physical->toArray();
        $entities = SchemaValues::map($data['entities']);
        $components = SchemaValues::map($draft['components']);
        $order = $draft['dependency_order'];
        assert(is_array($order));
        $tables = $up = $foreign = $dropForeign = [];
        foreach ($order as $component) {
            assert(is_string($component));
            $history = SchemaValues::map($components[$component]);
            $steps = $history['steps'];
            assert(is_array($steps));
            foreach ($steps as $value) {
                $step = SchemaValues::map($value);
                if ($step['action'] !== 'create') {
                    continue;
                }
                $entity = self::text($step['entity']);
                $spec = SchemaValues::map($entities[$entity]);
                $table = self::qualified(schema: $physical->location->schema, table: self::text($spec['table']));
                $tables[] = $table;
                $columns = [];
                $model = SchemaValues::map($spec['model']);
                $primary = SchemaValues::map($spec['primary']);
                foreach (SchemaValues::map($spec['columns']) as $name => $column) {
                    $definition = SchemaValues::map($column);
                    $identity = $model['incrementing'] === true && $primary['columns'] === [$name];
                    $columns[] = self::identifier($name).' '.$this->column(definition: $definition, identity: $identity);
                }
                $columns[] = 'CONSTRAINT '.self::identifier(self::text($primary['name'])).' PRIMARY KEY ('.self::columns($primary['columns']).')';
                foreach (SchemaValues::map($spec['checks']) as $value) {
                    $check = SchemaValues::map($value);
                    $columns[] = 'CONSTRAINT '.self::identifier(self::text($check['name'])).' CHECK ('.$this->predicate($check).')';
                }
                $up[] = 'CREATE TABLE '.$table.' ('.implode(', ', $columns).')';
                foreach (SchemaValues::map($spec['indexes']) as $value) {
                    $index = SchemaValues::map($value);
                    $up[] = 'CREATE '.($index['unique'] === true ? 'UNIQUE ' : '').'INDEX '.self::identifier(self::text($index['name'])).' ON '.$table.' ('.self::columns($index['columns']).')';
                }
                foreach (SchemaValues::map($spec['foreign_keys']) as $value) {
                    $key = SchemaValues::map($value);
                    $name = self::identifier(self::text($key['name']));
                    $foreign[] = 'ALTER TABLE '.$table.' ADD CONSTRAINT '.$name.' FOREIGN KEY ('.self::columns($key['columns']).') REFERENCES '.self::qualified(schema: self::text($key['schema']), table: self::text($key['table'])).' ('.self::columns($key['references']).') ON DELETE '.match ($key['on_delete']) {
                        'restrict' => 'RESTRICT', 'cascade' => 'CASCADE', 'set_null' => 'SET NULL', default => throw new \LogicException('Invalid compiled foreign key'),
                    };
                    $dropForeign[] = 'ALTER TABLE '.$table.' DROP CONSTRAINT '.$name;
                }
            }
        }
        SchemaValues::require(valid: count($tables) === count($entities), key: 'snapshot', rule: 'SNAPSHOT_ENTITY_ORDER_INVALID');

        return ['up' => [...$up, ...$foreign], 'down' => [...array_reverse($dropForeign), ...array_map(fn (string $table): string => 'DROP TABLE '.$table.' RESTRICT', array_reverse($tables))], 'tables' => $tables];
    }

    /** @param array<string, mixed> $definition */
    public function column(array $definition, bool $identity): string
    {
        $type = self::text($definition['type']);
        $sql = $this->type($definition);
        if ($definition['collation'] === 'C') {
            $sql .= ' COLLATE "C"';
        }
        if ($identity) {
            SchemaValues::require(valid: in_array($type, ['bigint', 'integer'], true) && $definition['hasDefault'] === false, key: 'identity', rule: 'SNAPSHOT_KEY_INVALID');
            $sql .= ' GENERATED BY DEFAULT AS IDENTITY';
        }
        if ($definition['hasDefault'] === true) {
            $default = $definition['default'];
            assert(is_string($default) || is_int($default) || is_bool($default) || $default === null);
            $sql .= ' DEFAULT '.self::literal($default);
        }

        return $sql.($definition['nullable'] === true ? '' : ' NOT NULL');
    }

    /** @param array<string, mixed> $definition */
    public function type(array $definition): string
    {
        return match (self::text($definition['type'])) {
            'uuid' => 'uuid', 'text' => 'text', 'bigint' => 'bigint', 'integer' => 'integer',
            'boolean' => 'boolean', 'json' => 'jsonb', 'timestamp' => 'timestamp(6) with time zone',
            'string' => 'varchar('.self::number($definition['length']).')',
            default => throw new \LogicException('Invalid compiled column'),
        };
    }

    /** @param array<string, mixed> $check */
    public function predicate(array $check): string
    {
        $columns = $check['columns'];
        $values = $check['values'];
        assert(is_array($columns) && is_array($values));
        $column = self::identifier(self::text($columns[0]));
        // PanelSchema is also constructible from data: never interpolate an unchecked bound.
        if ($check['kind'] === 'byte_length') {
            SchemaValues::require(valid: count($values) === 1 && preg_match('/^[1-9][0-9]{0,8}$/D', self::text($values[0])) === 1, key: 'check.values');
        }

        return match ($check['kind']) {
            'positive' => $column.' >= 1',
            'one_of' => $column.' IN ('.implode(', ', array_map(fn (mixed $value): string => self::literal(self::text($value)), $values)).')',
            'nonnull_iff' => '('.$column.' IS NOT NULL) = ('.self::identifier(self::text($columns[1])).' IS NOT DISTINCT FROM '.self::literal(self::text($values[0])).')',
            'byte_length' => 'octet_length('.$column.') BETWEEN 1 AND '.self::text($values[0]),
            'matches' => $column.'::text ~ '.self::literal(self::text($values[0])),
            'json_object' => 'jsonb_typeof('.$column.") = 'object'",
            default => throw new \LogicException('Invalid compiled predicate'),
        };
    }

    private static function text(mixed $value): string
    {
        assert(is_string($value));

        return $value;
    }

    private static function number(mixed $value): int
    {
        assert(is_int($value));

        return $value;
    }

    public static function columns(mixed $columns): string
    {
        assert(is_array($columns));

        return implode(', ', array_map(fn (mixed $column): string => self::identifier(self::text($column)), $columns));
    }

    public static function identifier(string $identifier): string
    {
        SchemaValues::require(valid: SchemaValues::identifier($identifier), key: 'identifier', rule: 'STORAGE_IDENTIFIER_INVALID');

        return '"'.$identifier.'"';
    }

    public static function qualified(string $schema, string $table): string
    {
        return self::identifier($schema).'.'.self::identifier($table);
    }

    public static function literal(string|int|bool|null $value): string
    {
        return match (true) {
            $value === null => 'NULL', is_bool($value) => $value ? 'TRUE' : 'FALSE', is_int($value) => (string) $value,
            // E-strings are explicit, independent of standard_conforming_strings.
            default => "E'".str_replace(['\\', "'"], ['\\\\', "''"], $value)."'",
        };
    }
}
